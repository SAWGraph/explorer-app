// The Analysis Question sentence has to describe the question that runs. A
// filter that narrows the SPARQL but leaves the sentence unchanged tells the
// user they asked something they did not, which is how Block C regions went
// unmentioned.
//
//   npm test             # verify
//   npx vitest run -u    # re-record the wording snapshot after an intended change
import { describe, expect, it } from 'vitest';
import { generateQuestion, type QuestionTotals } from '../src/utils/questionGenerator';
import { PREBUILT_QUERIES } from '../src/constants/prebuiltQueries';
import type { AnalysisQuestion, EntityBlock, EntityType } from '../src/types/query';
import { REPRESENTATIVE } from './questions/representative';
import { CRITICAL } from './questions/critical';
import {
  BLOCK_FILTERS,
  NO_OP_FILTERS,
  NO_OP_RELATIONSHIPS,
  RELATIONSHIPS,
  type BlockFilterCase,
} from './questions/filters';

const NEAR = { type: 'near', hops: 1 } as const;

// The other block needs a type; any type other than the one under test works.
const other = (type: EntityType): EntityType => (type === 'samples' ? 'facilities' : 'samples');

const onBlock = (side: 'A' | 'C', c: BlockFilterCase, filtered: boolean): AnalysisQuestion => {
  const block: EntityBlock = filtered ? { type: c.type, ...c.filter } : { type: c.type };
  const rest: EntityBlock = { type: other(c.type) };
  return side === 'A'
    ? { blockA: block, relationship: NEAR, blockC: rest }
    : { blockA: rest, relationship: NEAR, blockC: block };
};

const relQuestion = (relationship: AnalysisQuestion['relationship']): AnalysisQuestion => ({
  blockA: { type: 'samples' },
  relationship,
  blockC: { type: 'facilities' },
});

describe.each(['A', 'C'] as const)('Block %s', (side) => {
  it.each(BLOCK_FILTERS.map((c) => [c.name, c] as const))('%s changes the sentence', (_, c) => {
    expect(generateQuestion(onBlock(side, c, true))).not.toBe(generateQuestion(onBlock(side, c, false)));
  });

  it.each(NO_OP_FILTERS.map((c) => [c.name, c] as const))('%s leaves the sentence alone', (_, c) => {
    expect(generateQuestion(onBlock(side, c, true))).toBe(generateQuestion(onBlock(side, c, false)));
  });
});

describe('Relationship', () => {
  it.each(RELATIONSHIPS.map((c) => [c.name, c] as const))('%s changes the sentence', (_, c) => {
    expect(generateQuestion(relQuestion(c.to))).not.toBe(generateQuestion(relQuestion(c.from)));
  });

  it.each(NO_OP_RELATIONSHIPS.map((c) => [c.name, c] as const))('%s leaves the sentence alone', (_, c) => {
    expect(generateQuestion(relQuestion(c.to))).toBe(generateQuestion(relQuestion(c.from)));
  });
});

// "All counties" is decided against the county list of the block's own state.
it('collapses each block to "all counties" against its own state', () => {
  const allOf = (stateCode: string, n: number) => {
    const codes = Array.from({ length: n }, (_, i) => `${stateCode}${String(i).padStart(3, '0')}`);
    return { stateCode, countyCodes: codes, countyLabels: Object.fromEntries(codes.map((c) => [c, `County ${c}`])) };
  };
  const totals: QuestionTotals = { counties: { '17': 102, '23': 16 } };
  const text = generateQuestion(
    {
      blockA: { type: 'samples', region: allOf('17', 102) },
      relationship: NEAR,
      blockC: { type: 'facilities', region: allOf('23', 16) },
    },
    totals,
  );
  expect(text).toContain('samples in all counties in Illinois');
  expect(text).toContain('facilities in all counties in Maine');
});

// Wording snapshot: one sentence per recorded question and per editor control,
// so a wording change is a reviewable diff rather than a surprise in the UI.
it('renders the recorded sentences', async () => {
  const out = ['# Generated by tests/questionText.test.ts, do not hand-edit.', '# Re-record with: npx vitest run -u', ''];
  const add = (name: string, q: AnalysisQuestion) => out.push(`## ${name}`, `  ${generateQuestion(q)}`);

  for (const p of PREBUILT_QUERIES) add(`PREBUILT: ${p.id}`, p.question);
  for (const r of REPRESENTATIVE) add(`REPRESENTATIVE: ${r.name}`, r.question);
  for (const c of CRITICAL) add(`CRITICAL: ${c.name}`, c.question);
  for (const c of BLOCK_FILTERS) {
    add(`FILTER A: ${c.name}`, onBlock('A', c, true));
    add(`FILTER C: ${c.name}`, onBlock('C', c, true));
  }
  for (const c of RELATIONSHIPS) add(`RELATIONSHIP: ${c.to.type} ${JSON.stringify(c.to)}`, relQuestion(c.to));

  await expect(out.join('\n') + '\n').toMatchFileSnapshot('./__snapshots__/question-text.txt');
});
