// Golden-file snapshot of the SPARQL the planner generates. For input X (a
// question) the engine must produce Y (its step queries) unless something was
// changed on purpose. Questions come from the dashboard and from
// engine/tests/questions/; nothing here generates them.
//
//   npm test             # verify
//   npx vitest run -u    # re-record after an intended change
//
// No network: the pipeline steps only build query strings.
import { createHash } from 'node:crypto';
import { expect, it } from 'vitest';
import { planPipeline, type PipelineContext } from '../planner';
import { PREFIXES } from '../constants/prefixes';
import { PREBUILT_QUERIES } from '../constants/prebuiltQueries';
import { REPRESENTATIVE, type NamedQuestion } from './questions/representative';
import { CRITICAL } from './questions/critical';

const QUESTIONS: NamedQuestion[] = [
  ...PREBUILT_QUERIES.map((p) => ({ name: `PREBUILT: ${p.id}`, question: p.question })),
  ...REPRESENTATIVE.map((r) => ({ name: `REPRESENTATIVE: ${r.name}`, question: r.question })),
  ...CRITICAL.map((c) => ({ name: `CRITICAL: ${c.name}`, question: c.question })),
];

// Fixed IRIs so the VALUES clauses are deterministic.
const context = (question: NamedQuestion['question']): PipelineContext => ({
  question,
  targetIris: ['http://example.org/target/1', 'http://example.org/target/2'],
  anchorIris: ['http://example.org/anchor/1', 'http://example.org/anchor/2'],
  results: {},
});

// Whitespace churn is not a behaviour change. The PREFIX preamble is identical
// in every query, so it is recorded once instead of in every body.
const collapse = (q: string) => q.replace(/\s+/g, ' ').trim();
const PREFIX_BLOCK = collapse(PREFIXES);
const normalise = (q: string) => collapse(q).replace(PREFIX_BLOCK, '').trim();
const hash = (s: string) => createHash('sha256').update(s).digest('hex').slice(0, 12);

it('generates the recorded SPARQL for every question', async () => {
  const out = ['# Generated by engine/tests/queryGeneration.test.ts, do not hand-edit.', '# Re-record with: npx vitest run -u', ''];
  out.push('## PREFIXES', `SHARED [all] ${hash(PREFIX_BLOCK)}`, `  ${PREFIX_BLOCK}`);

  // Bodies are stored once, keyed by hash, so a change to a query shared by
  // many questions is one changed body plus one moved hash per question.
  const bodies = new Map<string, string>();
  for (const { name, question } of QUESTIONS) {
    out.push(`## ${name}`);
    const ctx = context(question);
    for (const step of planPipeline(question)) {
      const query = normalise(step.buildQuery(ctx));
      expect(query, `empty query: ${name} / ${step.type}`).not.toBe('');
      bodies.set(hash(query), query);
      out.push(`${step.type} [${step.endpoint}] ${hash(query)}`);
    }
  }

  out.push('', '# ---- query bodies, one line per distinct query ----');
  for (const [h, query] of [...bodies].sort(([a], [b]) => a.localeCompare(b))) out.push(`${h} ${query}`);

  await expect(out.join('\n') + '\n').toMatchFileSnapshot('./__snapshots__/query-shapes.txt');
});
